import asyncio
import sys

import cv2
import numpy as np
from aiortc import VideoStreamTrack
from av import VideoFrame

from utils import Fps, combinate_rgbd, downscale, print_exceptions

from pylibfreenect2 import Freenect2, SyncMultiFrameListener
from pylibfreenect2 import FrameType, Registration, Frame
from pylibfreenect2 import createConsoleLogger, setGlobalLogger, LoggerLevel
from pylibfreenect2 import OpenGLPacketPipeline, OpenCLPacketPipeline, CpuPacketPipeline

class Kinect2StreamTrack(VideoStreamTrack):
    def __init__(self, near, far, is_hue = True, show = True):
        super().__init__()
        self.near = near
        self.far = far

        self.fps = Fps()
        self.show = show
        self.is_hue = is_hue

        # --- Hardware Setup (adapted from kinect-record.py) ---
        try:
            self.pipeline = OpenGLPacketPipeline()
        except:
            try:
                self.pipeline = OpenCLPacketPipeline()
            except:
                self.pipeline = CpuPacketPipeline()

        # Setup Logger (optional, keeps console clean)
        logger = createConsoleLogger(LoggerLevel.Warning)
        setGlobalLogger(logger)

        self.fn = Freenect2()
        num_devices = self.fn.enumerateDevices()
        if num_devices == 0:
            print("No device connected!")
            sys.exit(1)

        serial = self.fn.getDeviceSerialNumber(0)
        self.device = self.fn.openDevice(serial, pipeline=self.pipeline)

        # Listen for all frame types
        self.listener = SyncMultiFrameListener(FrameType.Color | FrameType.Ir | FrameType.Depth)
        self.device.setColorFrameListener(self.listener)
        self.device.setIrAndDepthFrameListener(self.listener)

        self.device.start()

        # Registration setup to align depth to color
        self.registration = Registration(self.device.getIrCameraParams(), self.device.getColorCameraParams())

        # Pre-allocate frames for registration
        self.undistorted = Frame(512, 424, 4)
        self.registered = Frame(512, 424, 4)
        self.bigdepth = Frame(1920, 1082, 4)  # High-res depth mapping

    @print_exceptions
    async def recv(self):
        pts, time_base = await self.next_timestamp()

        # waitForNewFrame is blocking, so we run it in an executor to avoid freezing the event loop
        loop = asyncio.get_running_loop()
        frames = await loop.run_in_executor(None, self.listener.waitForNewFrame)

        color = frames["color"]
        depth = frames["depth"]

        # Apply registration (align depth to the high-res color camera)
        self.registration.apply(color, depth, self.undistorted, self.registered, bigdepth=self.bigdepth)

        # Process Color: Kinect returns BGRA (1080, 1920, 4), we need BGR for processing
        color_bgr = color.asarray()[:, :, :3]

        # Process Depth: bigdepth is (1082, 1920), we need (1080, 1920) to match color
        # We assume combinate_rgbd expects raw depth values or float
        depth_map = self.bigdepth.asarray(np.float32)
        depth_map = depth_map[0:1080, :]  # Crop extra 2 rows generated by bigdepth

        # Use utility to combine/visualize
        # Note: 'cuda' is hardcoded here based on your example, change if needed
        frame_bgr = combinate_rgbd(color_bgr, depth_map, self.near, self.far, self.is_hue, 'cuda')

        # Release the frames back to the listener immediately
        self.listener.release(frames)

        # Convert to RGB for WebRTC
        frame_rgb = cv2.cvtColor(frame_bgr, cv2.COLOR_BGR2RGB)

        # Performance logging
        self.fps.tickAndPrint()

        # Create VideoFrame
        video_frame = VideoFrame.from_ndarray(frame_rgb, format="rgb24")
        video_frame.pts = pts
        video_frame.time_base = time_base
        return video_frame

    def stop(self):
        if self.device:
            self.device.stop()
            self.device.close()
            print("Kinect device closed.")